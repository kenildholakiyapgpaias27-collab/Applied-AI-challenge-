#!/usr/bin/env python3
"""Write supabase/seed.sql from data/catalogue.json.

    python3 tools/seed_catalogue.py

The seed is an upsert: run it again after editing the catalogue and the database
catches up. Products that are no longer in the file are marked inactive (hidden
from the app) rather than deleted, so old plans and check-ins keep their links.
The catalogue version is a hash of the JSON; build.py embeds the same hash, so a
page only downloads the catalogue from the database when the two differ.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "catalogue.json"
OUT = ROOT / "supabase" / "seed.sql"
FLAGS = ["contains_fragrance", "contains_essential_oils", "contains_drying_alcohol",
         "contains_retinoid", "contains_aha", "contains_bha", "pregnancy_caution"]


def catalogue_version(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()[:12]


def q(v):
    """SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "array[" + ",".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def main():
    raw = SRC.read_bytes()
    cat = json.loads(raw)
    version = catalogue_version(raw)
    cols = ["id", "brand", "name", "category", "price_inr", "size", "key_actives", "inci",
            "skin_types", "concerns", *FLAGS, "comedogenic_risk", "finish", "spf", "pa_rating",
            "is_sponsored", "active"]
    rows, shades = [], []
    for p in cat:
        fl = (p.get("fl") or "0000000").ljust(7, "0")
        vals = [p["id"], p["b"], p["n"], p["c"], p.get("p"), p.get("sz"), p.get("a"), p.get("i"),
                p.get("st", []), p.get("con", []), *[fl[i] == "1" for i in range(7)],
                p.get("com"), p.get("fin"), p.get("spf"), p.get("pa"), bool(p.get("sp")), True]
        rows.append("(" + ",".join(q(v) for v in vals) + ")")
        for i, s in enumerate(p.get("s") or []):
            name, depth, ut, hx, cov = (list(s) + [None] * 5)[:5]
            shades.append("(" + ",".join(q(v) for v in [p["id"], name, depth, ut, hx, cov, i]) + ")")

    upd = ",".join(f"{c}=excluded.{c}" for c in cols if c != "id")
    ids = ",".join(q(p["id"]) for p in cat)
    sql = [
        "-- Generated by tools/seed_catalogue.py from data/catalogue.json. Do not edit by hand.",
        f"-- {len(cat)} products, {len(shades)} shades, catalogue version {version}",
        "begin;",
        f"insert into public.products ({','.join(cols)}) values",
        ",\n".join(rows),
        f"on conflict (id) do update set {upd};",
        f"update public.products set active=false where id not in ({ids});",
        "delete from public.shades where product_id in (select id from public.products);",
        "insert into public.shades (product_id,shade_name,depth,undertone,hex,coverage,sort_order) values",
        ",\n".join(shades) + ";",
        "insert into public.catalogue_meta (id,version,updated_at) values (true,"
        f"{q(version)},now()) on conflict (id) do update set version=excluded.version,updated_at=now();",
        "commit;",
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(sql), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}: {len(cat)} products, {len(shades)} shades, version {version}")


if __name__ == "__main__":
    main()
