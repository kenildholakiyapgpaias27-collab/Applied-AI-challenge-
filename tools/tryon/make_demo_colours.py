#!/usr/bin/env python3
"""Generate data/demo_colours.json: DEMO shade colours for the virtual try-on.

    python3 tools/tryon/make_demo_colours.py

The catalogue has no shade colours for Lipstick, Blush or Kajal / eyeliner, so the
try-on needs placeholder colours to show anything. These are NOT real product data:
every shade carries "demo": true and the try-on labels it on screen. They are never
written to data/catalogue.json, supabase/seed.sql or the database.

Deterministic: the shades for a product depend only on its id (SHA-256 seeded),
so re-running gives byte-identical output.
"""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CATS = ("Lipstick", "Blush", "Kajal / eyeliner")

# Shade families chosen to flatter light to deep Indian skin tones (name, hex)
LIP = [("Chai Nude", "#a0675a"), ("Rose Kulfi", "#b8646e"), ("Gulmohar Red", "#b3262f"), ("Jamun Berry", "#7a2340"),
       ("Masala Brick", "#9a3b2a"), ("Mauve Dusk", "#94606f"), ("Plum Silk", "#5e2238"), ("Coral Haat", "#d0604f"),
       ("Terracotta Clay", "#a54a35"), ("Kokum Maroon", "#6b1f24"), ("Cinnamon Brown", "#7d4a3c"), ("Sindoor Red", "#c22d2b")]
BLUSH = [("Peach Lassi", "#e39a7c"), ("Coral Bloom", "#e07a63"), ("Rose Petal", "#d07985"), ("Berry Glow", "#a5455f"),
         ("Terracotta Sun", "#c06a4c"), ("Brick Dust", "#a24f3e"), ("Plum Blush", "#8e4a62"), ("Bronze Dawn", "#a66a46")]
EYE = [("Kohl Black", "#141112"), ("Espresso Brown", "#3b2720"), ("Charcoal Smoke", "#2e2f33"), ("Midnight Navy", "#1d2742"),
       ("Plum Night", "#3e2236"), ("Peacock Green", "#1f4a43"), ("Bronze Kohl", "#5a3d26"), ("Graphite", "#3a3a3d")]
FAMILY = {"Lipstick": LIP, "Blush": BLUSH, "Kajal / eyeliner": EYE}


def finish_for(cat, name, r):
    n = name.lower()
    if cat == "Lipstick":
        if "gloss" in n:
            return "gloss"
        if "matte" in n or "liquid" in n:
            return "matte"
        if "tint" in n or "balm" in n:
            return "sheer"
        return ("satin", "creme")[r % 2]
    if cat == "Blush":
        if "cream" in n or "liquid" in n or "stick" in n:
            return "dewy"
        return ("matte", "satin")[r % 2]
    return "shimmer" if r % 5 == 0 and "kajal" not in n else "matte"


def jitter(hexcol, r):
    """Small, deterministic variation so shades differ between products."""
    rgb = [int(hexcol[i:i + 2], 16) for i in (1, 3, 5)]
    d = ((r >> 3) % 13) - 6          # -6..+6 brightness
    t = ((r >> 7) % 7) - 3           # -3..+3 warmth
    out = [rgb[0] + d + t, rgb[1] + d, rgb[2] + d - t]
    return "#" + "".join(f"{max(0, min(255, v)):02x}" for v in out)


def shades_for(p):
    seed = int(hashlib.sha256(p["id"].encode()).hexdigest(), 16)
    fam = FAMILY[p["c"]]
    n = 4 + seed % 5                                  # 4..8 shades
    start = (seed >> 11) % len(fam)
    step = 1 + (seed >> 17) % 3
    picked, k = [], 0
    while len(picked) < min(n, len(fam)):
        i = (start + k * step) % len(fam)
        if i not in picked:
            picked.append(i)
        k += 1
        if k > 4 * len(fam):
            step = 1
    out = []
    for j, i in enumerate(picked):
        r = (seed >> (j * 5)) & 0xFFFFF
        name, hx = fam[i]
        out.append({"name": name, "hex": jitter(hx, r), "finish": finish_for(p["c"], p["n"], r), "demo": True})
    return out


def build(catalogue):
    prods = {}
    for p in sorted(catalogue, key=lambda x: x["id"]):
        if p["c"] in CATS:
            prods[p["id"]] = {"c": p["c"], "n": p["n"], "shades": shades_for(p)}
    return {"note": "DEMO colours for the virtual try-on only. Not real product data. "
                    "Generated by tools/tryon/make_demo_colours.py; never written to the catalogue or database.",
            "demo": True, "products": prods}


def main():
    cat = json.loads((ROOT / "data" / "catalogue.json").read_text(encoding="utf-8"))
    data = build(cat)
    (ROOT / "data" / "demo_colours.json").write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    n = sum(len(v["shades"]) for v in data["products"].values())
    print(f"Wrote data/demo_colours.json: {len(data['products'])} products, {n} demo shades")


if __name__ == "__main__":
    main()
